-- unaccent() is only STABLE; wrap it so it can be used in indexes/triggers.
create or replace function public.mindsten_normalize(input text)
returns text
language sql
immutable
parallel safe
set search_path = public, extensions
as $$
  select lower(unaccent('unaccent'::regdictionary, coalesce(input, '')))
$$;

create or replace function public.mindsten_touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

