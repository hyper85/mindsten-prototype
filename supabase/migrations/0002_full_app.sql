create or replace function public.mindsten_distance_m(
  lat1 double precision, lng1 double precision, lat2 double precision, lng2 double precision
) returns double precision
language sql
immutable
parallel safe
as $$
  select 2 * 6371000 * asin(sqrt(
    power(sin(radians(lat2 - lat1) / 2), 2) +
    cos(radians(lat1)) * cos(radians(lat2)) * power(sin(radians(lng2 - lng1) / 2), 2)
  ))
$$;

create or replace function public.nearby_persons(
  p_lat double precision,
  p_lng double precision,
  p_radius_m double precision default 5000,
  p_limit int default 20
) returns table (person_id bigint, distance_m double precision)
language sql
stable
set search_path = public
as $$
  select p.id, public.mindsten_distance_m(p_lat, p_lng, p.lat, p.lng) as d
  from persons p
  where p.lat is not null and p.lng is not null
    -- cheap bounding box before the exact distance
    and p.lat between p_lat - (p_radius_m / 111000.0) and p_lat + (p_radius_m / 111000.0)
    and p.lng between p_lng - (p_radius_m / (111000.0 * greatest(cos(radians(p_lat)), 0.01)))
                  and p_lng + (p_radius_m / (111000.0 * greatest(cos(radians(p_lat)), 0.01)))
    and public.mindsten_distance_m(p_lat, p_lng, p.lat, p.lng) <= p_radius_m
  order by d asc, p.curated desc, p.id
  limit least(greatest(p_limit, 1), 200)
$$;

create or replace function public.search_persons(
  p_query text,
  p_limit int default 20
) returns table (person_id bigint, score real)
language sql
stable
set search_path = public, extensions
as $$
  with q as (select public.mindsten_normalize(p_query) as v)
  select p.id,
         greatest(word_similarity(q.v, p.search_name),
                  case when p.search_name like '%' || q.v || '%' then 1.0 else 0 end)::real as s
  from persons p, q
  where char_length(q.v) >= 2
    and (p.search_name like '%' || q.v || '%' or q.v <% p.search_name)
  order by s desc, p.curated desc, p.death_year desc nulls last
  limit least(greatest(p_limit, 1), 100)
$$;

-- Ranks persons against what was read off a gravestone.
-- score 0–100: name 0–60, years 0–30, distance 0–10.
create or replace function public.match_gravestone(
  p_names text[],
  p_birth_year int default null,
  p_death_year int default null,
  p_lat double precision default null,
  p_lng double precision default null,
  p_limit int default 5
) returns table (person_id bigint, score int, distance_m double precision)
language sql
stable
set search_path = public, extensions
as $$
  with names as (
    select public.mindsten_normalize(n) as v
    from unnest(coalesce(p_names, '{}')) as n
    where char_length(trim(n)) >= 2
  ),
  scored as (
    select p.id,
      coalesce((select max(word_similarity(names.v, p.search_name)) from names), 0) as name_sim,
      case
        when p_birth_year is null or p.birth_year is null then 0
        when p.birth_year = p_birth_year then 15
        when abs(p.birth_year - p_birth_year) = 1 then 8
        else -10
      end +
      case
        when p_death_year is null or p.death_year is null then 0
        when p.death_year = p_death_year then 15
        when abs(p.death_year - p_death_year) = 1 then 8
        else -10
      end as year_pts,
      case
        when p_lat is null or p_lng is null or p.lat is null or p.lng is null then null
        else public.mindsten_distance_m(p_lat, p_lng, p.lat, p.lng)
      end as dist
    from persons p
    where exists (select 1 from names where names.v <% p.search_name or p.search_name like '%' || names.v || '%')
       or (p_death_year is not null and p.death_year = p_death_year
           and p_birth_year is not null and p.birth_year = p_birth_year)
  )
  select id,
    greatest(0, least(100, round(
      name_sim * 60 + year_pts +
      case when dist is null then 0 when dist < 300 then 10 when dist < 3000 then 5 else 0 end
    )))::int as score,
    dist
  from scored
  order by score desc, dist asc nulls last
  limit least(greatest(p_limit, 1), 20)
$$;

